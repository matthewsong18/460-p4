package features.property_management;

import common.InputValidation;

/*+----------------------------------------------------------------------
 ||
 ||  Class Property
 ||
 ||      Author:  Matthew Song
 ||
 ||      Purpose:  Represents a property with an ID, type, and monthly
 ||                income. This record class provides a concise way to
 ||                model property data and includes built-in validation
 ||                for property type and income during instantiation.
 ||                It serves as a local representation of a property
 ||                tuple from the database.
 ||
 ||  Inherits From:  java.lang.Record
 ||
 ||      Interfaces:  None.
 ||
 |+-----------------------------------------------------------------------
 ||
 ||      Constants:  None.
 ||
 |+-----------------------------------------------------------------------
 ||
 ||   Constructors:  Property(Long property_id, String property_type, int property_monthly_income) (Canonical constructor, validation logic in compact constructor)
 ||                  Property(String property_type, int property_monthly_income) (Custom constructor delegating to canonical)
 ||
 ||  Class Methods:  None.
 ||
 ||  Inst. Methods:  Long property_id() // Accessor for property_id
 ||                  String property_type() // Accessor for property_type
 ||                  int property_monthly_income() // Accessor for property_monthly_income
 ||                  private void checkPropertyType(String propertyType)
 ||                  private void checkPropertyIncome(int propertyMonthlyIncome)
 ||                  // Standard record methods: equals(Object o), hashCode(), toString() are also implicitly provided.
 ||
 ++-----------------------------------------------------------------------*/
public record Property(
        Long property_id,
        String property_type,
        int property_monthly_income
) {
    /*---------------------------------------------------------------------
     |  Method Property (Custom Constructor)
     |
     |  Purpose:  Constructs a new Property object with a null ID. This is
     |            typically used when creating a new property record that
     |            has not yet been assigned an ID from the database.
     |            It delegates to the canonical constructor for actual
     |            object creation and validation.
     |
     |  Pre-condition:  property_type is not blank, property_monthly_income
     |                  is not negative (enforced by canonical/compact constructor).
     |
     |  Post-condition: A new Property object is created with the specified
     |                  type and income, and a null ID. Validation rules
     |                  defined in the compact constructor will have been applied.
     |
     |  Parameters:
     |      property_type -- The type of the property (e.g., "Apartment", "House").
     |                       Cannot be blank.
     |      property_monthly_income -- The monthly income generated by the
     |                                 property. Cannot be negative.
     |
     |  Returns:  None.
     *-------------------------------------------------------------------*/
    public Property(String property_type, int property_monthly_income) {
        this(null, property_type, property_monthly_income);
    }

    /*---------------------------------------------------------------------
     |  Method Property (Compact Constructor)
     |
     |  Purpose:  This compact constructor is automatically invoked by the
     |            canonical constructor. Its primary purpose here is to
     |            validate the arguments (property_type and
     |            property_monthly_income) before the fields of the record
     |            are initialized.
     |
     |  Pre-condition:  The parameters property_type and property_monthly_income
     |                  are about to be assigned to the record's fields.
     |
     |  Post-condition: The property_type and property_monthly_income fields
     |                  are validated. If validation fails, an
     |                  IllegalArgumentException is thrown, preventing the
     |                  object's creation. If validation passes, the fields
     |                  of the record will be initialized by the canonical
     |                  constructor.
     |
     |  Parameters:
     |      property_type -- (Implicit) The property type passed to the
     |                       canonical constructor.
     |      property_monthly_income -- (Implicit) The monthly income passed
     |                                 to the canonical constructor.
     |
     |  Returns:  None.
     *-------------------------------------------------------------------*/
    public Property {
        checkPropertyType(property_type);
        checkPropertyIncome(property_monthly_income);
    }

    /*---------------------------------------------------------------------
     |  Method checkPropertyType
     |
     |  Purpose:  Validates the property type string. It ensures that the
     |            property type is not null or blank (empty or whitespace only).
     |            This method supports the correct operation of its class by
     |            enforcing data integrity for the property_type field.
     |
     |  Pre-condition:  The propertyType string is provided.
     |
     |  Post-condition: If the propertyType is blank, an
     |                  IllegalArgumentException is thrown. Otherwise, the
     |                  method completes normally.
     |
     |  Parameters:
     |      propertyType -- The string representing the property type to
     |                      be validated.
     |
     |  Returns:  None.
     *-------------------------------------------------------------------*/
    private void checkPropertyType(String propertyType) {
        if (InputValidation.checkStringBlank(propertyType)) {
            throw new IllegalArgumentException("Property type cannot be blank");
        }
    }

    /*---------------------------------------------------------------------
     |  Method checkPropertyIncome
     |
     |  Purpose:  Validates the property's monthly income. It ensures that
     |            the income is not a negative value. This method supports
     |            the correct operation of its class by enforcing data
     |            integrity for the property_monthly_income field.
     |
     |  Pre-condition:  The propertyMonthlyIncome integer is provided.
     |
     |  Post-condition: If the propertyMonthlyIncome is less than 0, an
     |                  IllegalArgumentException is thrown. Otherwise, the
     |                  method completes normally.
     |
     |  Parameters:
     |      propertyMonthlyIncome -- The integer representing the property's
     |                               monthly income to be validated.
     |
     |  Returns:  None.
     *-------------------------------------------------------------------*/
    private void checkPropertyIncome(int propertyMonthlyIncome) {
        if (propertyMonthlyIncome < 0) {
            throw new IllegalArgumentException("Property Monthly income cannot be negative");
        }
    }
}