package features.member_management;

import common.InputValidation;

import java.sql.Date;

/*+----------------------------------------------------------------------
 ||
 ||  Class Member
 ||
 ||         Author:  Matthew Song
 ||                   Stephin Tomson
 ||
 ||        Purpose:  This class serves as a local representation of a member's data
 ||              as stored in a database. It is structured as a Java Record
 ||              to immutably hold member attributes like ID, name, contact
 ||              details, date of birth, and emergency contact. It also
 ||              incorporates validation logic to ensure data integrity upon
 ||              object creation.
 ||
 ||  Inherits From:  java.lang.Record (implicitly)
 ||
 ||     Interfaces:  java.io.Serializable (implicitly by virtue of being a record)
 ||
 |+-----------------------------------------------------------------------
 ||
 ||      Constants:  None.
 ||
 |+-----------------------------------------------------------------------
 ||
 ||   Constructors:
 ||                   Member(Long id, String name, String telephoneNumber, String email, Date dateOfBirth, Long emergencyContact) - Canonical constructor with validation.
 ||                   Member(String name, String telephoneNumber, String email, Date dateOfBirth, Long emergencyContact) - Service constructor for creating new members without an ID.
 ||
 ||  Class Methods:
 ||                   validateInputs(String name, String telephone, String email, Date dateOfBirth, Long emergencyContact): void - Validates all input fields for a member. (private static)
 ||                   checkName(String name): void - Validates the member's name. (private static)
 ||                   checkTelephone(String telephone): void - Validates the member's telephone number. (private static)
 ||                   checkEmail(String email): void - Validates the member's email. (private static)
 ||                   checkDateOfBirth(Date dateOfBirth): void - Validates the member's date of birth. (private static)
 ||                   checkEmergencyContact(Long emergencyContact): void - Validates the member's emergency contact number. (private static)
 ||
 ||  Inst. Methods:  (Accessor methods are automatically generated by the record for each component)
 ||                   id(): Long - Returns the member's ID.
 ||                   name(): String - Returns the member's name.
 ||                   telephoneNumber(): String - Returns the member's telephone number.
 ||                   email(): String - Returns the member's email.
 ||                   dateOfBirth(): Date - Returns the member's date of birth.
 ||                   emergencyContact(): Long - Returns the member's emergency contact number.
 ||                  (equals(Object obj): boolean, hashCode(): int, toString(): String are also implicitly provided and overridden)
 ||
 ++-----------------------------------------------------------------------*/
public record Member(
        Long id,
        String name,
        String telephoneNumber,
        String email,
        Date dateOfBirth,
        Long emergencyContact
) {

    /**
     * ---------------------------------------------------------------------
     * |  Method Member (Service Constructor)
     * |
     * |  Purpose:  This constructor is used for creating a new member instance
     * |            when the database ID has not yet been assigned (e.g., prior
     * |            to inserting the member record into the database). It
     * |            achieves this by invoking the canonical constructor with a
     * |            null value for the ID.
     * |
     * |  Pre-condition:  The provided name, telephoneNumber, email, dateOfBirth,
     * |                 and emergencyContact must adhere to the validation
     * |                 rules defined within the validateInputs method, which
     * |                 is called by the canonical constructor.
     * |
     * |  Post-condition: A new Member object is instantiated with the given
     * |                  details and a null ID. If any of the input validations
     * |                  fail within the canonical constructor, an
     * |                  IllegalArgumentException will be thrown.
     * |
     * |  Parameters:
     * |      name -- The full name of the member.
     * |      telephoneNumber -- The 10-digit telephone number of the member.
     * |      email -- The email address of the member.
     * |      dateOfBirth -- The date of birth of the member (java.sql.Date).
     * |      emergencyContact -- The 10-digit emergency contact number for the member.
     * |
     * |  Returns:  None (constructor).
     * -------------------------------------------------------------------
     */
    public Member(String name, String telephoneNumber, String email, Date dateOfBirth, Long emergencyContact) {
        this(null, name, telephoneNumber, email, dateOfBirth, emergencyContact);
    }

    /**
     * ---------------------------------------------------------------------
     * |  Method Member (Canonical Constructor)
     * |
     * |  Purpose:  This is the canonical constructor for the Member record. It is
     * |            responsible for initializing a Member object with all its
     * |            attributes. Crucially, it calls the validateInputs method
     * |            to ensure all provided data meets the required criteria
     * |            before the object is fully constructed.
     * |
     * |  Pre-condition:  None explicitly, as this constructor performs the
     * |                 validation itself.
     * |
     * |  Post-condition: If all input parameters are valid according to
     * |                  validateInputs, a Member object is successfully created
     * |                  and initialized with these parameters. If any validation
     * |                  fails, an IllegalArgumentException is thrown, and the
     * |                  object is not created.
     * |
     * |  Parameters: (Implicitly, the components of the record)
     * |      id -- The unique identifier for the member; can be null if not yet persisted.
     * |      name -- The full name of the member.
     * |      telephoneNumber -- The 10-digit telephone number of the member.
     * |      email -- The email address of the member.
     * |      dateOfBirth -- The date of birth of the member (java.sql.Date).
     * |      emergencyContact -- The 10-digit emergency contact number for the member.
     * |
     * |  Returns:  None (constructor).
     * -------------------------------------------------------------------
     */
    public Member {
        validateInputs(name, telephoneNumber, email, dateOfBirth, emergencyContact);
    }

    /**
     * ---------------------------------------------------------------------
     * |  Method validateInputs
     * |
     * |  Purpose:  This method serves as a centralized validation hub for all
     * |            attributes of a Member. It sequentially calls specific
     * |            checking methods for each attribute (name, telephone, email,
     * |            dateOfBirth, emergencyContact) to ensure data integrity.
     * |            This helps maintain the Member object in a consistent and
     * |            valid state.
     * |
     * |  Pre-condition:  None. The method is designed to take raw inputs.
     * |
     * |  Post-condition: If all individual validation checks pass, the method
     * |                  completes execution without returning any value or
     * |                  throwing exceptions. If any of the called check methods
     * |                  determine an input to be invalid, an
     * |                  IllegalArgumentException is thrown, halting further
     * |                  processing.
     * |
     * |  Parameters:
     * |      name -- The member's name string to be validated.
     * |      telephone -- The member's telephone number string to be validated.
     * |      email -- The member's email string to be validated.
     * |      dateOfBirth -- The member's date of birth (java.sql.Date) to be validated.
     * |      emergencyContact -- The member's emergency contact number (Long) to be validated.
     * |
     * |  Returns:  None.
     * -------------------------------------------------------------------
     */
    private static void validateInputs(String name, String telephone, String email, Date dateOfBirth,
                                       Long emergencyContact) {
        checkName(name);
        checkTelephone(telephone);
        checkEmail(email);
        checkDateOfBirth(dateOfBirth);
        checkEmergencyContact(emergencyContact);
    }

    /**
     * ---------------------------------------------------------------------
     * |  Method checkName
     * |
     * |  Purpose:  This method validates the member's name. It specifically
     * |            checks if the provided name string is blank (null or empty
     * |            after trimming whitespace).
     * |
     * |  Pre-condition:  The InputValidation.checkStringBlank(String) method
     * |                  must be accessible and correctly implemented to
     * |                  determine if a string is blank.
     * |
     * |  Post-condition: If the name is not blank, the method completes
     * |                  silently. If the name is found to be blank, an
     * |                  IllegalArgumentException is thrown with a descriptive
     * |                  message.
     * |
     * |  Parameters:
     * |      name -- The name string to be validated.
     * |
     * |  Returns:  None.
     * -------------------------------------------------------------------
     */
    private static void checkName(String name) {
        if (InputValidation.checkStringBlank(name)) {
            throw new IllegalArgumentException("Name cannot be blank");
        }
    }

    /**
     * ---------------------------------------------------------------------
     * |  Method checkTelephone
     * |
     * |  Purpose:  This method validates the member's telephone number. It
     * |            ensures two conditions: first, that the telephone number
     * |            is not blank, and second, that it consists of exactly 10
     * |            digits. This helps maintain a standard format for telephone
     * |            numbers.
     * |
     * |  Pre-condition:  The InputValidation.checkStringBlank(String) method
     * |                  must be accessible and correctly implemented.
     * |
     * |  Post-condition: If the telephone number is not blank and has exactly
     * |                  10 digits, the method completes silently. Otherwise,
     * |                  an IllegalArgumentException is thrown with a message
     * |                  indicating the specific validation failure (blank or
     * |                  incorrect length).
     * |
     * |  Parameters:
     * |      telephone -- The telephone number string to be validated.
     * |
     * |  Returns:  None.
     * -------------------------------------------------------------------
     */
    private static void checkTelephone(String telephone) {
        if (InputValidation.checkStringBlank(telephone)) {
            throw new IllegalArgumentException("Telephone number cannot be blank");
        }
        if (telephone.length() != 10) {
            throw new IllegalArgumentException("Telephone number must have 10 digits");
        }
    }

    /**
     * ---------------------------------------------------------------------
     * |  Method checkEmail
     * |
     * |  Purpose:  This method validates the member's email address. It
     * |            performs a basic check to ensure the email string is not
     * |            blank.
     * |
     * |  Pre-condition:  The InputValidation.checkStringBlank(String) method
     * |                  must be accessible and correctly implemented.
     * |
     * |  Post-condition: If the email string is not blank, the method
     * |                  completes silently. If the email is blank, an
     * |                  IllegalArgumentException is thrown.
     * |
     * |  Parameters:
     * |      email -- The email string to be validated.
     * |
     * |  Returns:  None.
     * -------------------------------------------------------------------
     */
    private static void checkEmail(String email) {
        if (InputValidation.checkStringBlank(email)) {
            throw new IllegalArgumentException("Email cannot be blank");
        }
    }

    /**
     * ---------------------------------------------------------------------
     * |  Method checkDateOfBirth
     * |
     * |  Purpose:  This method validates the member's date of birth. It
     * |            checks if the provided Date object is null. Ensuring a
     * |            date of birth is provided is important for member records.
     * |
     * |  Pre-condition:  None.
     * |
     * |  Post-condition: If the dateOfBirth object is not null, the method
     * |                  completes silently. If dateOfBirth is null, an
     * |                  IllegalArgumentException is thrown.
     * |
     * |  Parameters:
     * |      dateOfBirth -- The java.sql.Date object representing the member's
     * |                   date of birth to be validated.
     * |
     * |  Returns:  None.
     * -------------------------------------------------------------------
     */
    private static void checkDateOfBirth(Date dateOfBirth) {
        if (dateOfBirth == null) {
            throw new IllegalArgumentException("Date of birth cannot be blank");
        }
    }

    /**
     * ---------------------------------------------------------------------
     * |  Method checkEmergencyContact
     * |
     * |  Purpose:  This method validates the member's emergency contact number.
     * |            It performs two checks: first, that the emergency contact
     * |            number (a Long) is not null, and second, that it represents
     * |            a 10-digit number
     * |
     * |  Pre-condition:  None.
     * |
     * |  Post-condition: If the emergencyContact is not null and falls within
     * |                  the 10-digit range, the method completes silently.
     * |                  Otherwise, an IllegalArgumentException is thrown with a
     * |                  message indicating the specific validation failure
     * |                  (blank or incorrect number of digits).
     * |
     * |  Parameters:
     * |      emergencyContact -- The Long value representing the emergency
     * |                         contact number to be validated.
     * |
     * |  Returns:  None.
     * -------------------------------------------------------------------
     */
    private static void checkEmergencyContact(Long emergencyContact) {
        if (emergencyContact == null) {
            throw new IllegalArgumentException("Emergency contact cannot be blank");
        }
        if (emergencyContact < 1000000000L || emergencyContact > 9999999999L) {
            throw new IllegalArgumentException("Emergency contact must have 10 digits");
        }
    }

}